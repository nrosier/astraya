/**
 * Yemen fixed-star registry (#739): the baseline fixed-star table from
 * al-Fārisī's Zīj al-Muẓaffarī, as printed.
 *
 * Data plus a longitude helper. Nothing here is computed from an ephemeris.
 */

/**
 * @module FixedStarRegistry
 * @purpose The baseline fixed-star table from al-Fārisī's Zīj al-Muẓaffarī (Yemen, 13th century), as printed; data plus a longitude helper.
 * @conventions Positions are as printed; no value is corrected. Bracketed or missing values are kept as printed, not inferred. The 1.0° default orb is an Astraya convention, not cited.
 * @exports RegistryStar, YEMEN_FIXED_STARS, YEMEN_STAR_AUTHORITY, FIXED_STAR_ORB_CONVENTION, registryLongitude, yemenStarLongitudes
 */
import type { Degrees } from '../ephemeris/types.js';

/** One printed row of the Yemen star table. Values are kept as printed. */
export interface RegistryStar {
  readonly id: string;
  readonly arabicName: string;
  /** 0 = Aries ... 11 = Pisces, as in astrology/signs.ts. */
  readonly signIndex: number;
  /** The sign as printed, including any brackets, e.g. "(Gem)" or "[Sgr]". */
  readonly signPrinted: string;
  readonly degree: number;
  readonly minute: number;
  /** The latitude exactly as printed, e.g. "26", "7;20 (N)", "24;50". Not parsed. */
  readonly latitudeText: string;
  readonly latitudeHemisphere: 'N' | 'S' | null;
  readonly magnitudeText: string | null;
  /** Each printed temperament pair as one array of planet names. Empty when none printed. */
  readonly temperaments: readonly (readonly string[])[];
  readonly peters_knobel: string;
  readonly modernId: string | null;
  readonly notes: string | null;
  /**
   * Variant printed longitudes for this star. Variants are kept for the record and are
   * never used for conjunctions (see docs/FIXED_STAR_REGISTRY.md).
   */
  readonly variantLongitudes: readonly RegistryVariant[];
}

/** A variant printed longitude for a registry star, kept as printed. */
export interface RegistryVariant {
  readonly id: string;
  readonly signIndex: number;
  readonly degree: number;
  readonly minute: number;
}

