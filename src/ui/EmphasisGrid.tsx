/**
 * @module ui/EmphasisGrid
 * @purpose The element x modality grid on screen (#511, #821): flat 1px-bordered cells holding the bodies' glyphs, with row totals at the right and column totals along the bottom.
 * @conventions Screen only: the PDF and sheet export keep `chart/emphasis-grid`'s drawing. Hidden from assistive tech: the Elements & modalities table under it is the accessible equivalent. Colours come from semantic tokens in app.css. Glyph markup is generated by this app from computed data, never user-supplied.
 * @exports EmphasisGrid, EmphasisGridLabels
 */
import { useMemo } from 'react';
import type { EmphasisGridInput } from '../chart/emphasis-grid.js';
import { bodyGlyph, renderGlyph } from '../chart/glyphs.js';
import type { Element, Modality } from '../astrology/signs.js';
import { buildEmphasisGridModel, formatEmphasisTotal, MODALITY_COLUMNS } from './emphasis-grid-model.js';

export interface EmphasisGridLabels {
  readonly elements: Readonly<Record<Element, string>>;
  readonly modalities: Readonly<Record<Modality, string>>;
}

/** One body as a self-contained 100-unit glyph drawing, sized by CSS. */
function glyphSvg(key: string): string {
  const definition = bodyGlyph(key);
  if (!definition) return '';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" class="emphasis-screen-glyph">` +
    `${renderGlyph(definition, 50, 50, 100, `chart-glyph chart-glyph-${key}`)}</svg>`
  );
}

export function EmphasisGrid({
  input,
  labels,
}: {
  readonly input: EmphasisGridInput;
  readonly labels: EmphasisGridLabels;
}): React.JSX.Element {
  const model = useMemo(() => buildEmphasisGridModel(input), [input]);
  return (
    <div className="emphasis-screen-grid" aria-hidden="true">
      <span className="emphasis-screen-corner" />
      {MODALITY_COLUMNS.map((modality) => (
        <span key={modality} className="emphasis-screen-heading emphasis-screen-column-heading">
          {labels.modalities[modality]}
        </span>
      ))}
      <span className="emphasis-screen-corner" />
      {model.rows.map((row) => (
        <div key={row.element} className="emphasis-screen-row">
          <span className="emphasis-screen-heading emphasis-screen-row-heading">{labels.elements[row.element]}</span>
          {row.cells.map((cell) => (
            <div
              key={cell.modality}
              className="emphasis-screen-cell"
              // The app's own glyph drawings, from computed data.
              dangerouslySetInnerHTML={{ __html: cell.bodyKeys.map(glyphSvg).join('') }}
            />
          ))}
          <span className="emphasis-screen-total emphasis-screen-row-total">{formatEmphasisTotal(row.total)}</span>
        </div>
      ))}
      <span className="emphasis-screen-corner" />
      {MODALITY_COLUMNS.map((modality) => (
        <span key={modality} className="emphasis-screen-total emphasis-screen-column-total">
          {formatEmphasisTotal(model.columnTotals[modality])}
        </span>
      ))}
      <span className="emphasis-screen-corner" />
    </div>
  );
}
