/**
 * @module ui/AspectMatrixGrid
 * @purpose The on-screen aspect matrix (#820): an ARIA table of divs styled with the flat primitive tokens, its aspect cells selecting a pair on the wheel.
 * @conventions Screen only (D-shared-drawing): the sheet and PDF keep `renderAspectMatrixSvg`'s drawing, which this reuses only for its position maths and glyph registry. Columns are Icon, Name, Degree, Sign, Minute, House, then one per body; the lower triangle holds the aspects and the diagonal repeats each row's identifier. Name and House drop at 40rem and below. No exact-aspect highlight (D-820) and no total row. Colours come from the aspect-family tokens through the existing glyph classes; every rule lives in app.css under `.mgrid`.
 * @exports AspectMatrixGrid, AspectMatrixGridLabels, AspectMatrixGridSelection
 */
import { useMemo } from 'react';
import { formatSignedOrb, positionParts, type AspectMatrixInput, type MatrixBody } from '../chart/aspect-matrix.js';
import { bodyId } from '../chart/body-id.js';
import { aspectGlyph, bodyGlyph, renderGlyph, signGlyph, type GlyphDefinition } from '../chart/glyphs.js';
import { selectionKey } from '../interpretation/selection-key.js';
import type { Locale } from '../interpretation/schema.js';
import { signDisplayName } from './astro-names.messages.js';
import { useSymbolClass } from './symbol-setting.js';

/** The aspect keys of each colour family, matching the wheel's own grouping (hard warm, soft cool, minor green). */
const HARD_ASPECTS: ReadonlySet<string> = new Set(['semisquare', 'square', 'sesquiquadrate', 'opposition']);
const MINOR_ASPECTS: ReadonlySet<string> = new Set(['quintile', 'biquintile', 'quincunx']);

function familyClass(aspectKey: string): string {
  if (HARD_ASPECTS.has(aspectKey)) return 'mgrid-hard';
  if (MINOR_ASPECTS.has(aspectKey)) return 'mgrid-minor';
  return 'mgrid-soft';
}

export interface AspectMatrixGridLabels {
  readonly symbol: string;
  readonly name: string;
  readonly degree: string;
  readonly sign: string;
  readonly minute: string;
  readonly house: string;
  readonly retrograde: string;
}

export interface AspectMatrixGridSelection {
  readonly selectedKey: string | undefined;
  readonly onToggle: (key: string) => void;
  /** Selects the pair and opens the Wheel view on it (#898); when absent a click only toggles the selection. */
  readonly onShowOnWheel?: ((key: string) => void) | undefined;
  /** Whether both bodies are drawn on the wheel, i.e. the pair can be selected. */
  readonly canSelect: (aKey: string, bKey: string) => boolean;
}

/** A glyph from the app's registry in the reader's chosen symbol class, in its own 0-100 box. */
function Glyph({
  definition,
  className,
}: {
  readonly definition: GlyphDefinition;
  readonly className: string;
}): React.JSX.Element {
  return (
    <svg
      className="mgrid-glyph"
      viewBox="0 0 100 100"
      aria-hidden="true"
      focusable="false"
      // Generated by this app from its own glyph registry, never user-supplied markup.
      dangerouslySetInnerHTML={{ __html: renderGlyph(definition, 50, 50, 100, className) }}
    />
  );
}

/** A body's identifier: its glyph where one exists, else its short label (the angles: AC, MC). */
function BodyMark({ body }: { readonly body: MatrixBody }): React.JSX.Element {
  const definition = bodyGlyph(body.key);
  if (definition === undefined) return <span className="mgrid-label">{body.label}</span>;
  return <Glyph definition={definition} className={`chart-glyph chart-glyph-${body.key}`} />;
}

export function AspectMatrixGrid({
  input,
  label,
  labels,
  locale,
  describe,
  selection,
}: {
  readonly input: AspectMatrixInput;
  readonly label: string;
  readonly labels: AspectMatrixGridLabels;
  readonly locale: Locale;
  /** The accessible name of a pair's cell, e.g. "Sun Trine Moon". */
  readonly describe: (aKey: string, bKey: string, aspectKey: string) => string;
  readonly selection?: AspectMatrixGridSelection | undefined;
}): React.JSX.Element {
  // Read so a change of symbol class redraws the glyphs (renderGlyph reads it at draw time).
  useSymbolClass();
  const { bodies } = input;
  const byPair = useMemo(() => {
    const map = new Map<string, AspectMatrixInput['aspects'][number]>();
    for (const aspect of input.aspects) {
      const key = [aspect.aKey, aspect.bKey].sort().join(' ');
      if (!map.has(key)) map.set(key, aspect);
    }
    return map;
  }, [input.aspects]);

  if (bodies.length === 0) return <div className="mgrid-scroll" role="group" aria-label={label} />;

  return (
    <div className="mgrid-scroll" role="group" aria-label={label}>
      <div
        className="mgrid"
        role="table"
        aria-label={label}
        style={{ '--mgrid-n': bodies.length } as React.CSSProperties}
      >
        <div className="mgrid-display-contents" role="rowgroup">
          <div className="mgrid-display-contents" role="row">
            <div role="columnheader" className="mgrid-head mgrid-icon">
              <span className="sr-only">{labels.symbol}</span>
            </div>
            <div role="columnheader" className="mgrid-head mgrid-col-name">
              {labels.name}
            </div>
            <div role="columnheader" className="mgrid-head mgrid-num">
              {labels.degree}
            </div>
            <div role="columnheader" className="mgrid-head mgrid-ctr">
              {labels.sign}
            </div>
            <div role="columnheader" className="mgrid-head mgrid-num">
              {labels.minute}
            </div>
            <div role="columnheader" className="mgrid-head mgrid-ctr mgrid-col-house">
              {labels.house}
            </div>
            {bodies.map((body) => (
              <div key={body.key} role="columnheader" className="mgrid-head mgrid-ctr">
                <span className="sr-only">{body.name}</span>
                <span aria-hidden="true">
                  <BodyMark body={body} />
                </span>
              </div>
            ))}
          </div>
        </div>
        <div className="mgrid-display-contents" role="rowgroup">
          {bodies.map((row, rowIndex) => {
            const { signName, element, degree, minute } = positionParts(row.longitude);
            const signGlyphDefinition = signGlyph(signName);
            const signText = signDisplayName(signName, locale);
            return (
              <div key={row.key} className="mgrid-display-contents" role="row">
                <div role="rowheader" className="mgrid-cell mgrid-icon">
                  <span className="sr-only">{row.name}</span>
                  <span aria-hidden="true" className="mgrid-mark">
                    <BodyMark body={row} />
                  </span>
                  {row.retrograde === true && (
                    <abbr className="mgrid-retro" title={labels.retrograde} aria-label={labels.retrograde}>
                      R
                    </abbr>
                  )}
                </div>
                <div role="cell" className="mgrid-cell mgrid-lab mgrid-col-name" aria-hidden="true">
                  {row.name}
                </div>
                <div role="cell" className="mgrid-cell mgrid-num">
                  {String(degree).padStart(2, '0')}°
                </div>
                <div role="cell" className="mgrid-cell mgrid-ctr">
                  <span className="sr-only">{signText}</span>
                  {signGlyphDefinition !== undefined && (
                    <span aria-hidden="true" className="mgrid-mark">
                      <Glyph
                        definition={signGlyphDefinition}
                        className={`chart-sign-glyph chart-sign-glyph-${signName.toLowerCase()} chart-sign-element-${element}`}
                      />
                    </span>
                  )}
                </div>
                <div role="cell" className="mgrid-cell mgrid-num">
                  {String(minute).padStart(2, '0')}&apos;
                </div>
                <div role="cell" className="mgrid-cell mgrid-ctr mgrid-col-house">
                  {row.house}
                </div>
                {bodies.map((column, columnIndex) => {
                  if (columnIndex > rowIndex) return <div role="cell" key={column.key} className="mgrid-empty" />;
                  if (columnIndex === rowIndex) {
                    return (
                      <div role="cell" key={column.key} className="mgrid-cell mgrid-ctr mgrid-diag" aria-hidden="true">
                        <BodyMark body={row} />
                      </div>
                    );
                  }
                  const aspect = byPair.get([row.key, column.key].sort().join(' '));
                  if (aspect === undefined) return <div role="cell" key={column.key} className="mgrid-cell" />;
                  const glyph = aspectGlyph(aspect.aspectKey);
                  const direction = aspect.applying ? 'applying' : 'separating';
                  const name = describe(row.key, column.key, aspect.aspectKey);
                  const body = (
                    <>
                      {glyph !== undefined && (
                        <Glyph
                          definition={glyph}
                          className={`chart-aspect-glyph chart-aspect-glyph-${aspect.aspectKey} chart-aspect-${direction}`}
                        />
                      )}
                      <span className="mgrid-orb" aria-hidden="true">
                        <span>{formatSignedOrb(aspect.signedOrb)}</span>
                        <span className="mgrid-dir">{aspect.applying ? 'a' : 's'}</span>
                      </span>
                    </>
                  );
                  const cellClass = `mgrid-cell mgrid-aspect ${familyClass(aspect.aspectKey)}`;
                  if (selection?.canSelect(row.key, column.key) !== true) {
                    return (
                      <div role="cell" key={column.key} className={cellClass}>
                        <span className="mgrid-pair" role="img" aria-label={name}>
                          {body}
                        </span>
                      </div>
                    );
                  }
                  const active = selection;
                  const key = selectionKey.aspect(bodyId(row.key, 0), bodyId(column.key, 0));
                  return (
                    <div role="cell" key={column.key} className={cellClass}>
                      <button
                        type="button"
                        className="mgrid-pair"
                        aria-label={name}
                        aria-pressed={active.selectedKey === key}
                        onClick={() => {
                          (active.onShowOnWheel ?? active.onToggle)(key);
                        }}
                      >
                        {body}
                      </button>
                    </div>
                  );
                })}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}
