/**
 * The aspect matrix on screen (#511): the triangular grid the exported chart sheet has always carried, with
 * each aspect cell a button that selects that pair on the wheel through the shared selection keys.
 */
/**
 * @module ui/AspectMatrix
 * @purpose Draws the chart's aspect matrix as a view of its own and wires its cells to the wheel's selection.
 * @conventions The markup is `renderAspectMatrixSvg`'s own (the same drawing the sheet export uses), with its cells made focusable buttons by that renderer's `interaction` option; clicks and Enter/Space are read back through `selectionKeyForTarget`, so a cell selects exactly what the Aspects table's "Show" button does. Static when no selection is supplied (the PDF export).
 * @exports AspectMatrix
 */
import { useMemo } from 'react';
import type { KeyboardEvent, MouseEvent } from 'react';
import { renderAspectMatrixSvg, type AspectMatrixInput } from '../chart/aspect-matrix.js';
import { bodyId } from '../chart/body-id.js';
import { selectionKey } from '../interpretation/selection-key.js';
import { selectionKeyForTarget } from './wheel-interaction.js';

/** The drawing's width in its own units, shown 1:1 (CSS caps its width here) so its text is as large as the page's. */
const MATRIX_WIDTH = 960;

export interface AspectMatrixSelection {
  readonly selectedKey: string | undefined;
  readonly onToggle: (key: string) => void;
  /** Whether both bodies are drawn on the wheel, i.e. the pair can be selected. */
  readonly canSelect: (aKey: string, bKey: string) => boolean;
  /** The accessible name of a pair's cell, e.g. "Sun Trine Moon". */
  readonly describe: (aKey: string, bKey: string, aspectKey: string) => string;
}

export function AspectMatrix({
  input,
  label,
  selection,
}: {
  readonly input: AspectMatrixInput;
  readonly label: string;
  readonly selection?: AspectMatrixSelection | undefined;
}): React.JSX.Element {
  const selectedKey = selection?.selectedKey;
  const svg = useMemo(() => {
    const { markup, height } = renderAspectMatrixSvg(
      input,
      { x: 0, y: 0, width: MATRIX_WIDTH },
      selection === undefined
        ? undefined
        : {
            describe: (a, b, aspect) =>
              selection.canSelect(a.key, b.key) ? selection.describe(a.key, b.key, aspect.aspectKey) : undefined,
            isSelected: (aKey, bKey) => selectedKey === selectionKey.aspect(bodyId(aKey, 0), bodyId(bKey, 0)),
          },
    );
    return (
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${String(MATRIX_WIDTH)} ${height.toFixed(2)}" ` +
      `class="chart-sheet chart-aspect-matrix">${markup}</svg>`
    );
  }, [input, selection, selectedKey]);

  const toggleFrom = (target: Element): void => {
    const key = selectionKeyForTarget(target);
    if (key?.startsWith('aspect:') === true) selection?.onToggle(key);
  };

  return (
    <div
      className="chart-matrix-view"
      role="group"
      aria-label={label}
      // The drawing is generated by this app from data it just computed, never user-supplied markup.
      dangerouslySetInnerHTML={{ __html: svg }}
      onClick={(event: MouseEvent<HTMLDivElement>) => {
        if (event.target instanceof Element) toggleFrom(event.target);
      }}
      onKeyDown={(event: KeyboardEvent<HTMLDivElement>) => {
        if (event.key !== 'Enter' && event.key !== ' ') return;
        if (!(event.target instanceof Element) || event.target.closest('.chart-matrix-pair') === null) return;
        event.preventDefault();
        toggleFrom(event.target);
      }}
    />
  );
}
