/**
 * Astrocartography (ACG) and Local Space map for a saved person (#171).
 *
 * Structured like `PeriodicTransitView.tsx`: same worker-ephemeris lifecycle, same
 * person-not-found / incomplete-moment / unknown-time-accuracy gating — ACG lines move
 * about 15° of longitude per hour of birth-time error, so an unknown birth time makes this
 * screen as meaningless as it makes `TransitView.tsx`.
 *
 * The map itself (`renderAcgMapSvg`) is embedded and exported exactly like `ChartView.tsx`'s
 * wheel: `dangerouslySetInnerHTML` on screen, `standaloneSvg` + `downloadText`/`svgToPngBlob`
 * for SVG/PNG export — same trust boundary (the markup is entirely generated by this app from
 * data it just computed, never user-supplied).
 */
/**
 * @module AstrocartographyView
 * @purpose Renders the Astrocartography (ACG) and Local Space map screen for a saved person's natal chart.
 * @conventions Gated like PeriodicTransitView/TransitView on a known birth time (ACG lines shift ~15° longitude per hour of time error); embeds the SVG map via `dangerouslySetInnerHTML` and exports it through `standaloneSvg`/`downloadText`/`svgToPngBlob`, matching ChartView's trust-boundary pattern for app-generated markup. Reads interpretive text from the shared wheel corpus via `resolvePlacementText`.
 * @exports AstrocartographyView
 */
import { GlossaryText } from './GlossaryText.js';
import { StatusMessage } from './primitives/StatusMessage.js';
import { personHref, routeHref } from './route.js';
import { useEffect, useMemo, useState } from 'react';
import { resolvePlacementText } from '../interpretation/compose.js';
import { useEphemerisProvider } from './EphemerisProviderContext.js';
import { renderAcgMapSvg, type AcgMapInput } from '../chart/acg-map.js';
import { acgMapLabels } from './acg-map-labels.js';
import { bodyById } from '../astrology/bodies.js';
import { degreesInSign, signOf } from '../astrology/signs.js';
import {
  computeAstrocartography,
  EXTENDED_ACG_BODY_IDS,
  TRADITIONAL_ACG_BODY_IDS,
  type AstrocartographyData,
} from '../domain/astrocartography.js';
import { ALL_LINE_TYPES, DEFAULT_MAP_SETTINGS, relocationOf, type LineType, type MapSettings } from './map-settings.js';
import { MapSettingsDialog } from './MapSettingsDialog.js';
import { Disclosure } from './primitives/Disclosure.js';
import { PageHeader } from './PageHeader.js';
import { bodyDisplayName, signDisplayName } from './astro-names.messages.js';
import { astrocartographyViewMessages } from './AstrocartographyView.messages.js';
import { useLocale } from './locale.js';
import { useMessages } from './messages.js';
import { PersonNotFound } from './PersonNotFound.js';
import { useStoreState } from './store-context.js';
import type { BodyId, GeoPosition } from '../ephemeris/types.js';
import type { CorpusEntry, Locale } from '../interpretation/schema.js';
import { wheelCorpus } from './wheel-corpus.js';
import { useStableMoment } from './use-stable-moment.js';
import { BackLink } from './BackLink.js';

function lineTypeLabels(t: typeof astrocartographyViewMessages.en): Record<LineType, string> {
  return { MC: t.mc, IC: t.ic, AC: t.ac, DC: t.dc };
}

type Load =
  | { readonly kind: 'loading' }
  | { readonly kind: 'ready'; readonly data: AstrocartographyData }
  | { readonly kind: 'error'; readonly message: string };

function bodyName(body: BodyId, locale: Locale): string {
  return bodyDisplayName(bodyById(body)?.key ?? String(body), locale);
}

/** `18°34' Libra`-style label for an ecliptic longitude. */
function signDegreeLabel(longitude: number, locale: Locale): string {
  const degrees = Math.floor(degreesInSign(longitude));
  const minutes = Math.round((degreesInSign(longitude) - degrees) * 60);
  return `${String(degrees)}°${String(minutes).padStart(2, '0')}' ${signDisplayName(signOf(longitude).name, locale)}`;
}

export function AstrocartographyView({ personId }: { personId: string }): React.JSX.Element {
  const state = useStoreState();
  const person = state.people.get(personId);
  const personMoment = useStableMoment(person?.moment);
  const t = useMessages(astrocartographyViewMessages);
  const [locale] = useLocale();
  const { provider } = useEphemerisProvider();
  // What the map is drawn from. Edited as a draft in the Map settings dialog and replaced as a whole on Apply, so
  // one commit is one recalculation and opening or cancelling the dialog never changes the map (#512).
  const [settings, setSettings] = useState<MapSettings>(DEFAULT_MAP_SETTINGS);
  const { lineTypes, bodies, localSpace } = settings;
  const [load, setLoad] = useState<Load>({ kind: 'loading' });
  // True while a recalculation runs. The last valid map stays on screen meanwhile, marked as updating, never blanked.
  const [updating, setUpdating] = useState(false);
  // The reviewed text of each line (#427): the mechanical sentence until it arrives.
  const [corpus, setCorpus] = useState<readonly CorpusEntry[]>([]);
  // The coastlines (#667), loaded as their own chunk only when this screen opens.
  const [coastline, setCoastline] = useState<string | undefined>(undefined);
  useEffect(() => {
    let cancelled = false;
    void import('../chart/coastline-110m.js').then(
      ({ COASTLINE_110M_PATH }) => {
        if (!cancelled) setCoastline(COASTLINE_110M_PATH);
      },
      () => {
        // Without coastlines the map still shows its grid and lines.
      },
    );
    return () => {
      cancelled = true;
    };
  }, []);
  useEffect(() => {
    let cancelled = false;
    wheelCorpus(locale).then(
      (loaded) => {
        if (!cancelled) setCorpus(loaded);
      },
      () => undefined,
    );
    return () => {
      cancelled = true;
    };
  }, [locale]);

  const relocationPlace: GeoPosition | undefined = useMemo(
    () => relocationOf({ relocationLat: settings.relocationLat, relocationLon: settings.relocationLon }),
    [settings.relocationLat, settings.relocationLon],
  );

  useEffect(() => {
    if (personMoment === undefined || provider === undefined) return undefined;
    const moment = personMoment;
    const effect = { cancelled: false };
    setUpdating(true);

    void (async () => {
      try {
        const data = await computeAstrocartography(moment, provider, {
          bodies,
          lineTypes,
          localSpace,
          ...(relocationPlace === undefined ? {} : { relocationPlace }),
        });
        if (!effect.cancelled) {
          setLoad({ kind: 'ready', data });
          setUpdating(false);
        }
      } catch (error) {
        if (!effect.cancelled) {
          setLoad({ kind: 'error', message: error instanceof Error ? error.message : String(error) });
          setUpdating(false);
        }
      }
    })();

    return () => {
      effect.cancelled = true;
    };
  }, [personMoment, provider, bodies, lineTypes, localSpace, relocationPlace]);

  const data = load.kind === 'ready' ? load.data : undefined;
  const map = useMemo(() => {
    if (data === undefined) return undefined;
    const input: AcgMapInput = {
      lines: data.lines,
      localSpaceLines: data.localSpaceLines,
      natalPlace: data.natalPlace,
      ...(relocationPlace === undefined ? {} : { relocationPlace }),
      ...(coastline === undefined ? {} : { coastline }),
    };
    // Line names and a legend drawn into the map itself (#667), so the download reads on its own too.
    return renderAcgMapSvg(input, { labels: acgMapLabels(locale) });
  }, [data, relocationPlace, locale, coastline]);

  if (person === undefined) {
    return <PersonNotFound />;
  }

  if (person.moment === undefined) {
    return (
      <main className="shell">
        <BackLink fallback={personHref(personId)} />
        <PageHeader title={t.astrocartographyFallback} titleTerm="astrocartography" />
        <p>
          {t.notCompleteMap(person.displayName || t.thisPerson)} <a href={personHref(personId)}>{t.personPageLink}</a>.
        </p>
      </main>
    );
  }

  if (person.timeAccuracy === 'unknown') {
    return (
      <main className="shell">
        <BackLink fallback={personHref(personId)} />
        <PageHeader title={t.astrocartographyFallback} titleTerm="astrocartography" />
        <p>
          <GlossaryText text={t.needsKnownTime(person.displayName || t.thisPerson)} />
        </p>
      </main>
    );
  }

  return (
    <main className="shell">
      <BackLink fallback={personHref(personId)} />
      <PageHeader
        title={person.displayName ? t.heading(person.displayName) : t.astrocartographyFallback}
        titleTerm="astrocartography"
      >
        <a href={routeHref({ kind: 'export-builder', personId, section: 'astrocartography' })}>{t.exportPdf}</a>
      </PageHeader>
      <p className="hint">
        <GlossaryText text={t.hint} />
      </p>

      <MapSettingsDialog applied={settings} onApply={setSettings} lineTypeLabels={lineTypeLabels(t)} />
      {data?.relocatedHouses !== undefined && (
        <p>
          {t.relocatedAscendantMidheaven(
            signDegreeLabel(data.relocatedHouses.ascendant, locale),
            signDegreeLabel(data.relocatedHouses.midheaven, locale),
          )}
        </p>
      )}

      {(load.kind === 'loading' || updating) && (
        <StatusMessage kind={load.kind === 'loading' ? 'loading' : 'updating'}>
          {load.kind === 'loading' ? t.calculating : t.updating}
        </StatusMessage>
      )}

      {load.kind === 'error' && <StatusMessage kind="error">{t.error(load.message)}</StatusMessage>}

      {map !== undefined && (
        <>
          <div
            className={updating ? 'acg-map acg-map-updating' : 'acg-map'}
            aria-busy={updating}
            // Entirely generated by this app from data it just computed — never user-supplied
            // markup — the same trust boundary `ChartView.tsx` documents for its own wheel.
            aria-hidden="true"
            dangerouslySetInnerHTML={{ __html: map.markup }}
          />

          {lineTypes.length > 0 && bodies.length > 0 && (
            <section className="acg-meanings" aria-labelledby="acg-meanings-heading">
              <h2 id="acg-meanings-heading">{t.meaningsHeading}</h2>
              <p className="hint">
                <GlossaryText text={t.meaningsHint} />
              </p>
              {[...TRADITIONAL_ACG_BODY_IDS, ...EXTENDED_ACG_BODY_IDS]
                .filter((body) => bodies.includes(body))
                .map((body) => {
                  const key = bodyById(body)?.key ?? String(body);
                  return (
                    <Disclosure
                      key={body}
                      title={bodyName(body, locale)}
                      summary={t.selectedLines(lineTypes.length)}
                      showLabel={t.showMeanings}
                      hideLabel={t.hideMeanings}
                    >
                      <dl>
                        {ALL_LINE_TYPES.filter((lineType) => lineTypes.includes(lineType)).map((lineType) => (
                          <div key={lineType}>
                            <dt>{lineTypeLabels(t)[lineType]}</dt>
                            <dd>
                              {resolvePlacementText(
                                { category: 'astro-line', body: key, angle: lineType },
                                locale,
                                corpus,
                              )}
                            </dd>
                          </div>
                        ))}
                      </dl>
                    </Disclosure>
                  );
                })}
            </section>
          )}
        </>
      )}
    </main>
  );
}
