/**
 * Generates src/chart/coastline-110m.ts, the astrocartography map's coastline (#667), from Natural Earth's
 * 1:110m coastline GeoJSON. Natural Earth is in the public domain.
 *
 * The input is not fetched here: download the pinned release file and pass its path, so the output is reproducible
 * and the script needs no network.
 *
 *   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_coastline.geojson
 *   node scripts/build-coastline.mjs ne_110m_coastline.geojson
 *
 * The file's SHA-256 is checked against the one below, so a different download fails loudly instead of quietly
 * changing the map. The output is one SVG path in degree space (x = longitude + 180, y = 90 − latitude, a 360 × 180
 * box), with relative coordinates rounded to 0.1°, which the map scales to its own width.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_coastline.geojson';
const SOURCE_SHA256 = '851f581ff5ffb844deed8ae1a9ce22e3c4bb3d74fa342cadb5d8e39b41ae7c3c';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src', 'chart', 'coastline-110m.ts');

const input = process.argv[2];
if (input === undefined) {
  console.error('usage: node scripts/build-coastline.mjs <ne_110m_coastline.geojson>');
  process.exit(1);
}
const raw = await readFile(input);
const digest = createHash('sha256').update(raw).digest('hex');
if (digest !== SOURCE_SHA256) {
  console.error(`unexpected SHA-256 ${digest}; expected the Natural Earth v5.1.2 file (${SOURCE_SHA256})`);
  process.exit(1);
}

const tenth = (value) => Math.round(value * 10) / 10;
const number = (value) => String(tenth(value) === 0 ? 0 : tenth(value));
const parts = [];
for (const feature of JSON.parse(raw.toString('utf8')).features) {
  const { type, coordinates } = feature.geometry;
  const lines = type === 'LineString' ? [coordinates] : coordinates;
  for (const line of lines) {
    const points = line.map(([longitude, latitude]) => [tenth(longitude + 180), tenth(90 - latitude)]);
    const [first] = points;
    const steps = [];
    for (let index = 1; index < points.length; index++) {
      const dx = points[index][0] - points[index - 1][0];
      const dy = points[index][1] - points[index - 1][1];
      if (tenth(dx) !== 0 || tenth(dy) !== 0) steps.push(`${number(dx)} ${number(dy)}`);
    }
    parts.push(`M${number(first[0])} ${number(first[1])}l${steps.join(' ')}`);
  }
}

const source = `/**
 * Natural Earth 1:110m coastline (v5.1.2, public domain) as one SVG path for the astrocartography map (#667).
 * Generated by scripts/build-coastline.mjs from ${SOURCE_URL}; do not edit by hand.
 */
/**
 * @module chart/coastline-110m
 * @purpose The world's coastlines as an SVG path in degree space (x = longitude + 180, y = 90 − latitude), drawn under the astrocartography map's lines (#667).
 * @conventions Generated, not hand-written; loaded with a dynamic import() only where a map is drawn, so it stays out of every other chunk.
 * @exports COASTLINE_110M_PATH
 */
export const COASTLINE_110M_PATH =
  '${parts.join('')}';
`;
await writeFile(OUT, source);
console.log(`wrote ${OUT} (${String(source.length)} bytes)`);
